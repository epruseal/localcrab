def test_install_pack_does_not_touch_healthy_current_shape_schema(tmp_path, monkeypatch):
    """Regression guard: a current-shape schema with no stale required=False
    (e.g. generated by an already-fixed install, or a manifest with no
    overlap) must still be skipped and left byte-for-byte untouched, exactly
    as before this change.
    """
    healthy = (
        "# Auto-generated by schema pack 'overlappack' v1.0.0\n"
        + yaml.safe_dump(
            {
                "type": "Widget",
                "version": "1.0.0",
                "space": "concept",
                "pack": "overlappack",
                "properties": {
                    "name": {"type": "string", "required": True},
                    "description": {"type": "string", "required": False},
                },
            },
            sort_keys=False,
        )
    )
    types_dir = _install_stale_current_shape_pack(tmp_path, monkeypatch, healthy)
    before = (types_dir / "Widget.yaml").read_text(encoding="utf-8")

    result = pack_registry.install_pack("overlappack")
    assert result["skipped"] == ["Widget"]

    after = (types_dir / "Widget.yaml").read_text(encoding="utf-8")
    assert after == before


