def test_installed_pack_stub_files_have_current_shape():
    """Live-directory regression check for issue #38.

    schema_pack_install artifacts (schemas/types/*.yaml with a `pack:`
    field) are gitignored, so a fresh checkout/CI runner normally has none
    of them -- only the hand-written core types. In that case there is
    nothing to check, and this must SKIP rather than pass, because a silent
    pass here is indistinguishable from "verified clean" -- which is
    exactly the kind of false confidence that let the original stale-stub
    bug go unnoticed. The tmp_path-fixture tests above
    (test_install_pack_migrates_legacy_shape_stub etc.) are what actually
    exercise the detection/migration logic in CI; this test only adds value
    in an environment (e.g. a real local install) that has pack-generated
    files on disk.
    """
    generated = [
        (path, data)
        for path in sorted(schema_loader.SCHEMAS_DIR.glob("*.yaml"))
        if isinstance((data := yaml.safe_load(path.read_text(encoding="utf-8"))), dict)
        and data.get("pack")
    ]
    if not generated:
        pytest.skip(
            "no pack-generated schema stubs present in this checkout "
            "(schema_pack_install output is gitignored) -- nothing to scan here"
        )

    stale = [path.name for path, data in generated if "properties" not in data]
    assert stale == [], f"legacy-shape schema stub(s) found, run install_pack to migrate: {stale}"


def _install_overlap_pack(tmp_path, monkeypatch, existing_widget_file=None):
    """Set up a pack whose manifest declares the same field in both
    `required` and `optional` (issue #107), optionally with a pre-existing
    legacy-shape Widget.yaml to route install_pack through the migration
    branch instead of the fresh-create branch.
    """
    packs_dir = tmp_path / "packs"
    types_dir = tmp_path / "types"
    packs_dir.mkdir()
    types_dir.mkdir()

    manifest = {
        "name": "overlappack",
        "version": "1.0.0",
        "types": ["Widget"],
        "spaces": ["concept"],
        "type_specs": {
            "Widget": {
                "space": "concept",
                "required": ["name"],
                "optional": ["name", "description"],  # #107: same field, both lists
            }
        },
    }
    (packs_dir / "overlappack.yaml").write_text(yaml.safe_dump(manifest), encoding="utf-8")
    monkeypatch.setattr(pack_registry, "_PACKS_DIR", packs_dir)
    monkeypatch.setattr(pack_registry, "_TYPES_DIR", types_dir)
    monkeypatch.setattr(schema_loader, "SCHEMAS_DIR", types_dir)
    schema_loader.load_type_schema.cache_clear()

    if existing_widget_file is not None:
        (types_dir / "Widget.yaml").write_text(existing_widget_file, encoding="utf-8")

    return types_dir


def test_install_pack_required_wins_over_manifest_optional_overlap(tmp_path, monkeypatch):
    """Issue #107: manifest `type_specs.Widget` lists `name` in BOTH
    `required` and `optional`. `_build_type_schema`'s optional-fields loop
    used to overwrite whatever the required-fields loop wrote, with no
    existence check -- unlike the `extra_required`/`extra_optional` handling
    a few lines down in the same function, which already guards with
    `if field_name in/not in properties`. required must win here too.
    """
    types_dir = _install_overlap_pack(tmp_path, monkeypatch)
    result = pack_registry.install_pack("overlappack")
    assert result["created"] == ["Widget"]

    data = yaml.safe_load((types_dir / "Widget.yaml").read_text(encoding="utf-8"))
    assert data["properties"]["name"]["required"] is True
    assert data["properties"]["description"]["required"] is False

    schema_loader.load_type_schema.cache_clear()
    missing = validate_node_properties("Widget", {"description": "x"})
    assert missing.valid is False
    assert "name" in missing.error


def test_install_pack_warns_on_manifest_required_optional_overlap(tmp_path, monkeypatch, caplog):
    """Issue #107 asks that the contradiction itself be surfaced, not just
    silently resolved in required's favour -- a pack author who lists the
    same field twice made a mistake and should be told.
    """
    _install_overlap_pack(tmp_path, monkeypatch)
    with caplog.at_level("WARNING"):
        pack_registry.install_pack("overlappack")
    assert any(
        "name" in rec.message and "required" in rec.message and "optional" in rec.message
        for rec in caplog.records
    )


def test_install_pack_migration_report_does_not_contradict_itself_on_overlap(tmp_path, monkeypatch, caplog):
    """Issue #107 (codex design-review round 1 counterexample): the
    migration branch computes `revived_required`/`revived_optional`
    independently from the manifest's `required`/`optional` lists. When
    those two manifest lists themselves overlap on a field missing from the
    old on-disk file, both `revived_required` and `revived_optional` used
    to include that field -- `revived_manifest_fields` then reported `name`
    as simultaneously revived-required and revived-optional, contradicting
    itself (the same class of contradiction PR #104's review already closed
    between `preserved_extra_fields` and `revived_manifest_fields`).
    """
    legacy = {
        "node_type": "Widget",
        "pack": "overlappack",
        "required": [],
        "optional": ["description"],  # old file never had `name` at all
    }
    existing = "# Auto-generated by schema pack 'overlappack' v1.0.0\n" + yaml.safe_dump(legacy)
    types_dir = _install_overlap_pack(tmp_path, monkeypatch, existing_widget_file=existing)

    with caplog.at_level("WARNING"):
        result = pack_registry.install_pack("overlappack")
    assert result["migrated"] == ["Widget"]

    revived = result["revived_manifest_fields"]["Widget"]
    assert "name" in revived["required"]
    assert "name" not in revived["optional"]  # must not claim `name` both ways

    data = yaml.safe_load((types_dir / "Widget.yaml").read_text(encoding="utf-8"))
    assert data["properties"]["name"]["required"] is True


