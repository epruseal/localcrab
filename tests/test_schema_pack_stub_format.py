def test_install_pack_repairs_stale_current_shape_schema_from_before_fix(tmp_path, monkeypatch):
    """Issue #107 (codex review, PR #336, P1): a schema generated BEFORE this
    fix already has `properties["name"]["required"] == False` on disk (the
    overlap bug's output). `install_pack` used to skip every current-shape
    file unconditionally (355-357), so a bare reinstall never reached the
    fixed `_build_type_schema` and the stale False persisted forever. A
    reinstall must repair it.
    """
    stale = (
        "# Auto-generated by schema pack 'overlappack' v1.0.0\n"
        + yaml.safe_dump(
            {
                "type": "Widget",
                "version": "1.0.0",
                "space": "concept",
                "pack": "overlappack",
                "properties": {
                    "name": {"type": "string", "required": False},
                    "description": {"type": "string", "required": False},
                },
            },
            sort_keys=False,
        )
    )
    types_dir = _install_stale_current_shape_pack(tmp_path, monkeypatch, stale)

    result = pack_registry.install_pack("overlappack")
    assert "Widget" in result["migrated"]

    data = yaml.safe_load((types_dir / "Widget.yaml").read_text(encoding="utf-8"))
    assert data["properties"]["name"]["required"] is True
    assert data["properties"]["description"]["required"] is False

    schema_loader.load_type_schema.cache_clear()
    missing = validate_node_properties("Widget", {"description": "x"})
    assert missing.valid is False
    assert "name" in missing.error


