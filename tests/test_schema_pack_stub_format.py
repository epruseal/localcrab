"""
Tests for opencrab.schemas.pack_registry stub generation.

Regression coverage for: generated type stubs used a `node_type/pack/
required/optional` shape that grammar.validator.validate_node_properties
never read (it only looks at `schema.get("properties", {})`), so installed
packs were validated as no-ops. install_pack must emit `type/version/space/
properties` schemas that the validator actually enforces.
"""

from __future__ import annotations

import yaml
import pytest

from opencrab.grammar.validator import validate_node_properties
from opencrab.schemas import loader as schema_loader
from opencrab.schemas import pack_registry


@pytest.fixture
def tmp_pack_env(tmp_path, monkeypatch):
    packs_dir = tmp_path / "packs"
    types_dir = tmp_path / "types"
    packs_dir.mkdir()
    types_dir.mkdir()

    manifest = {
        "name": "testpack",
        "version": "1.0.0",
        "description": "Test pack for stub-format regression coverage.",
        "types": ["Widget"],
        "spaces": ["concept"],
        "type_specs": {
            "Widget": {
                "space": "concept",
                "required": ["name"],
                "optional": ["description"],
            }
        },
    }
    (packs_dir / "testpack.yaml").write_text(yaml.safe_dump(manifest), encoding="utf-8")

    monkeypatch.setattr(pack_registry, "_PACKS_DIR", packs_dir)
    monkeypatch.setattr(pack_registry, "_TYPES_DIR", types_dir)
    monkeypatch.setattr(schema_loader, "SCHEMAS_DIR", types_dir)
    schema_loader.load_type_schema.cache_clear()
    yield types_dir
    schema_loader.load_type_schema.cache_clear()


def test_install_pack_generates_validator_compatible_schema(tmp_pack_env):
    types_dir = tmp_pack_env
    result = pack_registry.install_pack("testpack")
    assert result["created"] == ["Widget"]

    stub_path = types_dir / "Widget.yaml"
    assert stub_path.exists()
    content = stub_path.read_text(encoding="utf-8")
    assert "Auto-generated by schema pack 'testpack'" in content
    assert "pack: testpack" in content  # uninstall's generated-file detection relies on this

    data = yaml.safe_load(content)
    assert data["type"] == "Widget"
    assert data["space"] == "concept"
    assert "properties" in data
    assert data["properties"]["name"]["required"] is True
    assert data["properties"]["description"]["required"] is False


def test_validator_enforces_required_property_from_pack_manifest(tmp_pack_env):
    pack_registry.install_pack("testpack")
    schema_loader.load_type_schema.cache_clear()

    missing = validate_node_properties("Widget", {"description": "x"})
    assert missing.valid is False
    assert "name" in missing.error

    ok = validate_node_properties("Widget", {"name": "Foo"})
    assert ok.valid is True


def test_uninstall_removes_generated_stub(tmp_pack_env):
    pack_registry.install_pack("testpack")
    result = pack_registry.uninstall_pack("testpack")
    assert result["removed"] == ["Widget"]
    assert not (tmp_pack_env / "Widget.yaml").exists()
